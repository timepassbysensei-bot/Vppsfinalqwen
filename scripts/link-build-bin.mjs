#!/usr/bin/env node
/**
 * Deploy compatibility shim (runs automatically after `bun install` / `npm install`).
 *
 * Some hosted build runners execute the build step as a bare script name, e.g.
 * `bunx build` / `npx build`, instead of `bun run build`. bunx resolves a name
 * like that from `node_modules/.bin` first, and since this project has no
 * dependency that ships a `build` binary, the runner fails with:
 *
 *   error: could not determine executable to run for package build
 *   /bin/bash: line 1: vite: command not found
 *
 * This script places a tiny `build` executable in `node_modules/.bin` that runs
 * `scripts/build.mjs`, so both styles work:
 *   bun run build      ← the documented command
 *   bunx build         ← what a few runners use
 *
 * It is generated at install time on purpose: files in git lose their executable
 * bit on some hosts, and a generated shim always has the right mode. It is a
 * no-op when the project has not been installed yet.
 */
import { chmodSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const binDir = resolve(root, "node_modules", ".bin");
const entry = resolve(root, "scripts", "build.mjs");

if (!existsSync(entry)) {
  // Nothing to point at (e.g. a production install of a published tarball).
  process.exit(0);
}

try {
  mkdirSync(binDir, { recursive: true });

  const shim = [
    "#!/bin/sh",
    "# Auto-generated by scripts/link-build-bin.mjs — runs this project's production build.",
    `exec "${process.execPath}" "${entry}" "$@"`,
    "",
  ].join("\n");

  const shimPath = resolve(binDir, "build");
  writeFileSync(shimPath, shim, "utf8");
  chmodSync(shimPath, 0o755);
  console.log("✔ Added node_modules/.bin/build shim (lets `bunx build` run the site build).");
} catch (error) {
  // Never fail an install because of this convenience shim.
  console.warn(`• Skipped the build shim: ${error instanceof Error ? error.message : String(error)}`);
}
